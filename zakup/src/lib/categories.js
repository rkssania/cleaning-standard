import { norm } from './normalize.js';

export const CATEGORIES = [
  'Медоборудование и изделия',
  'Мебель и хранение',
  'Навигация',
  'Оргтехника и связь',
  'Санитария/дозаторы/отходы',
  'Хозяйственное и уборка',
  'Бытовая техника и кухня',
];

// Порядок важен: первое совпадение побеждает. Если ничего не подошло — медоборудование.
const RAW = [
  [CATEGORIES[0], /аппарат|кроват|каталк|носилк|инфуз|шприц|облучател|рециркулятор|стерилиз|автоклав|тонометр|термометр|ивл|монитор пациент|прикроватн\w* монитор|дефибрилл|весы|ростомер|штатив|бактерицид|операцион|пациент|фармацевт|гемо|плазм|тромбо|центрифуг|анализатор|микроскоп|кислород|отсос|светильник медиц|ингалятор|пульсоксиметр|электрокардио|экг/],
  [CATEGORIES[2], /навигац|указател|табличк|информационн\w* стенд|стенд информац|информационн\w* табличк|пиктограмм|вывеск|схем\w* эвакуац|план эвакуац|нумерац|стенд/],
  [CATEGORIES[5], /швабр|ведро|ведер|тряпк|щетк|совок|веник|уборочн|пылесос|моющ|губк|салфетк|перчатк|мешк|инвентар|стремянк|комбайн|таз(?: |$)|ветош|рукав для швабр|моп|флаундер/],
  [CATEGORIES[4], /бак(?: |$)|класс [абв]|дозатор|диспенсер|урна|мусор|отход|ерш|держател|сушилк\w* для рук|полотенцедерж|бумагодерж|мыльниц|утилиз|санитар|бахил/],
  [CATEGORIES[6], /холодильник|микроволнов|свч|чайник|кофемашин|кофеварк|кулер|плита|плитка|посудомо|стиральн|сушильн|тостер|термопот|мультиварк|посуд|тарелк|чашк|кружк|вилк|ложк|кухонн|утюг|водонагрев/],
  [CATEGORIES[3], /компьютер|ноутбук|монитор|принтер|мфу|сканер|телефон|факс|роутер|коммутатор|камера|видеонаблюд|моноблок|клавиатур|мышь|ибп|проектор|телевизор|вызов|интерком|рация|планшет|оргтехник|шредер|точка доступа|wifi|wi fi/],
  [CATEGORIES[1], /стол|стул|кресл|шкаф|стеллаж|тумб|полк|вешалк|диван|банкетк|кушетк|ширм|локер|скамь|табурет|комод|пуф|зеркал|штор|жалюзи|рецепц|стойк|шкафчик|сейф/],
];

const RULES = RAW.map(([cat, re]) => [cat, new RegExp('(?:^| )(?:' + re.source + ')')]);

export function classify(name) {
  const n = norm(name);
  for (const [cat, re] of RULES) if (re.test(n)) return cat;
  return CATEGORIES[0];
}
