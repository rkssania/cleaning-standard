const BY_NO = new Map(ROOMS.map((r) => [r[0], r]));
export const roomLabel = (no) => `${BY_NO.get(no)[1]} (пом. ${no})`;
export const ROOM_LABELS = ROOMS.map(([no]) => roomLabel(no));

