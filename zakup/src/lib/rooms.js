/** Приводит название помещения из заявки к названию по плану и навигации; незнакомые названия не меняет. */
export function canonRoom(name) {
  const raw = String(name ?? '').trim();
  const s = raw.toLowerCase().replace(/ё/g, 'е');
  let m;
  if ((m = raw.match(/^П[1-9] · пом\. (\d+)$/)) && BY_NO.has(+m[1])) return roomLabel(+m[1]);
  if ((m = raw.match(/^Палата (\d+) \((?:ШО|ШД)\)$/)) && BY_NO.has(+m[1]) && BY_NO.get(+m[1])[1].startsWith('Палата')) return roomLabel(+m[1]);
  if ((m = raw.match(/^Тамбур (\d+),/)) && BY_NO.has(+m[1])) return roomLabel(+m[1]);
  if (/^санузел,/i.test(raw)) {
    const all = [...raw.matchAll(/пом\. (\d+)/g)];
    const last = all.length ? +all[all.length - 1][1] : 0;
    if (BY_NO.has(last)) return roomLabel(last);
  }
  for (const [re, no] of KEYWORDS) if (re.test(s)) return roomLabel(no);
  return raw;
}
